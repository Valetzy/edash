-- profiles: everyone can read all profiles (needed to show "assigned to" names); only self can update own row
create policy "profiles_select_all" on profiles for select using (auth.uid() is not null);
create policy "profiles_update_own" on profiles for update using (id = auth.uid());

-- programs / school_terms: readable by all signed-in users; writable by registrar & president
create policy "programs_select" on programs for select using (auth.uid() is not null);
create policy "programs_write" on programs for insert with check (auth_role() in ('registrar','president'));
create policy "programs_update" on programs for update using (auth_role() in ('registrar','president'));

create policy "terms_select" on school_terms for select using (auth.uid() is not null);
create policy "terms_write" on school_terms for insert with check (auth_role() in ('registrar','president'));
create policy "terms_update" on school_terms for update using (auth_role() in ('registrar','president'));

-- students: readable by all signed-in users; writable by registrar
create policy "students_select" on students for select using (auth.uid() is not null);
create policy "students_insert" on students for insert with check (auth_role() = 'registrar');
create policy "students_update" on students for update using (auth_role() = 'registrar');

-- enrollments: readable by all signed-in users; writable by registrar
create policy "enrollments_select" on enrollments for select using (auth.uid() is not null);
create policy "enrollments_insert" on enrollments for insert with check (auth_role() = 'registrar');
create policy "enrollments_update" on enrollments for update using (auth_role() = 'registrar');

-- student_cases: readable by all; only career_guidance/president can update (assign/resolve)
create policy "cases_select" on student_cases for select using (auth.uid() is not null);
create policy "cases_update" on student_cases for update using (auth_role() in ('career_guidance','president'));

-- follow_up_visits: readable by all; only career_guidance can insert; author can update own entries
create policy "visits_select" on follow_up_visits for select using (auth.uid() is not null);
create policy "visits_insert" on follow_up_visits for insert with check (auth_role() = 'career_guidance');
create policy "visits_update" on follow_up_visits for update using (visited_by = auth.uid());

