create extension if not exists "pgcrypto";

-- ---------------------------------------------------------------------------
-- ENUMS
-- ---------------------------------------------------------------------------
create type user_role as enum ('registrar', 'career_guidance', 'president');
create type enrollment_status as enum ('enrolled', 'graduated', 'dropped', 'shifted');
create type semester_type as enum ('1st', '2nd', 'summer');
create type case_status as enum ('pending', 'investigating', 'resolved');
create type case_type as enum ('dropout', 'shifted');
create type visit_outcome as enum ('re_enrolled', 'confirmed_dropout', 'confirmed_transfer_school', 'unreachable', 'other');

-- ---------------------------------------------------------------------------
-- PROFILES  (one row per auth.users row, created on signup via trigger below)
-- ---------------------------------------------------------------------------
create table profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  role user_role not null,
  created_at timestamptz not null default now()
);

-- Auto-create a profile row when someone signs up. Role/full_name are passed
-- in via the signup call's `options.data` (see src/lib/supabase.ts signUp()).
create or replace function handle_new_user()
returns trigger as $$
begin
  insert into public.profiles (id, full_name, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'full_name', 'Unnamed User'),
    coalesce((new.raw_user_meta_data->>'role')::user_role, 'registrar')
  );
  return new;
end;
$$ language plpgsql security definer;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function handle_new_user();

-- Helper used throughout RLS policies
create or replace function auth_role()
returns user_role as $$
  select role from public.profiles where id = auth.uid();
$$ language sql stable security definer;

-- ---------------------------------------------------------------------------
-- PROGRAMS / COURSES
-- ---------------------------------------------------------------------------
create table programs (
  id uuid primary key default gen_random_uuid(),
  code text unique not null,
  name text not null,
  created_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- SCHOOL TERMS  (term_order drives the "what came before this term" logic)
-- ---------------------------------------------------------------------------
create table school_terms (
  id uuid primary key default gen_random_uuid(),
  school_year text not null,        -- e.g. '2025-2026'
  semester semester_type not null,
  term_order int not null unique,   -- 1, 2, 3 ... strictly increasing, chronological
  is_closed boolean not null default false, -- true once detect_enrollment_changes has run for it
  created_at timestamptz not null default now(),
  unique (school_year, semester)
);

-- ---------------------------------------------------------------------------
-- STUDENTS
-- ---------------------------------------------------------------------------
create table students (
  id uuid primary key default gen_random_uuid(),
  student_no text unique not null,
  first_name text not null,
  last_name text not null,
  contact_number text,
  address text,
  created_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- ENROLLMENTS  (one row per student per term)
-- ---------------------------------------------------------------------------
create table enrollments (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null references students(id) on delete cascade,
  program_id uuid not null references programs(id),
  term_id uuid not null references school_terms(id),
  year_level int not null,
  status enrollment_status not null default 'enrolled',
  created_by uuid references profiles(id),
  created_at timestamptz not null default now(),
  unique (student_id, term_id)
);

create index on enrollments (term_id);
create index on enrollments (program_id);
create index on enrollments (student_id);

-- ---------------------------------------------------------------------------
-- STUDENT CASES  (auto-generated by detect_enrollment_changes)
-- ---------------------------------------------------------------------------
create table student_cases (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null references students(id) on delete cascade,
  last_enrollment_id uuid references enrollments(id),
  case_type case_type not null,
  from_program_id uuid references programs(id),
  to_program_id uuid references programs(id),   -- only set when case_type = 'shifted'
  status case_status not null default 'pending',
  assigned_to uuid references profiles(id),
  created_at timestamptz not null default now(),
  resolved_at timestamptz
);

create index on student_cases (case_type);
create index on student_cases (status);

-- ---------------------------------------------------------------------------
-- FOLLOW-UP VISITS  (career guidance house-to-house visit log)
-- ---------------------------------------------------------------------------
create table follow_up_visits (
  id uuid primary key default gen_random_uuid(),
  case_id uuid not null references student_cases(id) on delete cascade,
  visited_by uuid references profiles(id),
  visit_date date not null default current_date,
  reason_category text,   -- financial, health, distance, family, working, not_interested, transferred_school, other
  reason_notes text,
  outcome visit_outcome,
  created_at timestamptz not null default now()
);

create index on follow_up_visits (case_id);

-- ---------------------------------------------------------------------------
-- DETECTION FUNCTION
-- Call this after the registrar has finished entering a term's enrollments.
-- Compares the given term against the immediately preceding term_order and
-- inserts dropout / shifted cases for students who vanished or changed program.
-- ---------------------------------------------------------------------------
create or replace function detect_enrollment_changes(p_term_id uuid)
returns table (dropout_count int, shifted_count int) as $$
declare
  v_current_order int;
  v_prev_term_id uuid;
  v_dropout_count int := 0;
  v_shifted_count int := 0;
begin
  select term_order into v_current_order from school_terms where id = p_term_id;
  if v_current_order is null then
    raise exception 'Unknown term_id %', p_term_id;
  end if;

  select id into v_prev_term_id from school_terms where term_order = v_current_order - 1;

  if v_prev_term_id is not null then
    -- DROPOUT: enrolled previous term, absent this term, not already a case
    with new_dropouts as (
      insert into student_cases (student_id, last_enrollment_id, case_type, from_program_id, status)
      select pe.student_id, pe.id, 'dropout', pe.program_id, 'pending'
      from enrollments pe
      where pe.term_id = v_prev_term_id
        and pe.status = 'enrolled'
        and not exists (select 1 from enrollments ce where ce.student_id = pe.student_id and ce.term_id = p_term_id)
        and not exists (select 1 from student_cases sc where sc.last_enrollment_id = pe.id)
      returning 1
    )
    select count(*) into v_dropout_count from new_dropouts;

    -- SHIFTED: enrolled previous term, enrolled this term under a different program
    with new_shifts as (
      insert into student_cases (student_id, last_enrollment_id, case_type, from_program_id, to_program_id, status)
      select pe.student_id, pe.id, 'shifted', pe.program_id, ce.program_id, 'pending'
      from enrollments pe
      join enrollments ce on ce.student_id = pe.student_id and ce.term_id = p_term_id
      where pe.term_id = v_prev_term_id
        and pe.status = 'enrolled'
        and ce.program_id <> pe.program_id
        and not exists (select 1 from student_cases sc where sc.last_enrollment_id = pe.id)
      returning 1
    )
    select count(*) into v_shifted_count from new_shifts;
  end if;

  update school_terms set is_closed = true where id = p_term_id;

  return query select v_dropout_count, v_shifted_count;
end;
$$ language plpgsql security definer;

