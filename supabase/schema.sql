-- Enrollment headcount per program per term
create or replace view program_term_stats as
select
  t.id as term_id, t.school_year, t.semester, t.term_order,
  p.id as program_id, p.name as program_name, p.code as program_code,
  count(*) filter (where e.status = 'enrolled') as enrolled_count
from enrollments e
join programs p on p.id = e.program_id
join school_terms t on t.id = e.term_id
group by t.id, t.school_year, t.semester, t.term_order, p.id, p.name, p.code
order by t.term_order, p.name;

-- Term-over-term retention/dropout/shift rate, school-wide and per program
create or replace view retention_rates as
select
  t.id as term_id, t.school_year, t.semester, t.term_order,
  p.id as program_id, p.name as program_name,
  count(*) filter (where sc.id is null) as retained_count,
  count(*) filter (where sc.case_type = 'dropout') as dropout_count,
  count(*) filter (where sc.case_type = 'shifted') as shifted_count,
  count(*) as prior_cohort_size
from enrollments pe
join school_terms t on t.id = pe.term_id
join programs p on p.id = pe.program_id
left join student_cases sc on sc.last_enrollment_id = pe.id
where pe.status = 'enrolled'
group by t.id, t.school_year, t.semester, t.term_order, p.id, p.name
order by t.term_order, p.name;

-- Full case detail, joined for the UI (career guidance + president)
create or replace view case_details as
select
  sc.id, sc.case_type, sc.status, sc.created_at, sc.resolved_at, sc.assigned_to,
  s.id as student_id, s.student_no, s.first_name, s.last_name, s.contact_number, s.address,
  fp.name as from_program_name, tp.name as to_program_name,
  t.school_year, t.semester,
  fv.reason_category, fv.reason_notes, fv.outcome, fv.visit_date
from student_cases sc
join students s on s.id = sc.student_id
join enrollments e on e.id = sc.last_enrollment_id
join school_terms t on t.id = e.term_id
left join programs fp on fp.id = sc.from_program_id
left join programs tp on tp.id = sc.to_program_id
left join lateral (
  select * from follow_up_visits v where v.case_id = sc.id order by v.visit_date desc limit 1
) fv on true;

-- Dropout reasons breakdown (for president charts)
create or replace view dropout_reasons_summary as
select reason_category, count(*) as total
from follow_up_visits
where reason_category is not null
group by reason_category
order by total desc;

